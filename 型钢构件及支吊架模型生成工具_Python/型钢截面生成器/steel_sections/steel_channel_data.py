DEFAULT_PROFILE = "20a"


def profile_names():
    """Return profile names in the same order as the standards table."""
    return tuple(CHANNEL_DATA.keys())


def get_section(profile_name):
    """Return an independent section-data dictionary for *profile_name*."""
    try:
        section = dict(CHANNEL_DATA[profile_name])
    except KeyError:
        raise ValueError("Unsupported channel profile: {0}".format(profile_name))
    validate_section(section)
    return section


def validate_section(section):
    """Raise ``ValueError`` when a section cannot produce a valid outline."""
    required = ("H", "B", "tw", "tf", "r", "Z0")
    missing = [name for name in required if name not in section]
    if missing:
        raise ValueError("Missing channel dimensions: {0}".format(", ".join(missing)))

    h, b = section["H"], section["B"]
    tw, tf, r = section["tw"], section["tf"], section["r"]
    if min(h, b, tw, tf, r) <= 0.0:
        raise ValueError("All channel dimensions must be positive.")
    if b <= tw + r:
        raise ValueError("B must be greater than tw + r.")
    if h <= 2.0 * (tf + r):
        raise ValueError("H is too small for two flange fillets.")
    if not 0.0 < section["Z0"] < b:
        raise ValueError("Z0 must lie between the web and flange tip.")
