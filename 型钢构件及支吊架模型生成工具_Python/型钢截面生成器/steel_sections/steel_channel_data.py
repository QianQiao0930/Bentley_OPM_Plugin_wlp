"""Nominal parallel-leg channel-section data in millimetres.

The drawing tool models the section stated in the brief: parallel flange faces,
a uniform web, and two inside fillets.  ``Z0`` is the published/reference
centroid distance from the outside face of the web; the actual insertion
centroid is calculated from the exact geometry generated by ``channel_geometry.py``.
"""

from __future__ import division

import math


def _parallel_leg_z0(h, b, tw, tf, r):
    """Return the centroid distance from the outside web face in mm.

    This matches the simplified, parallel-leg profile that the plug-in draws.
    It intentionally does not attempt to model the flange taper of other
    channel-section families.
    """
    web_area = tw * h
    flange_area = 2.0 * (b - tw) * tf
    sharp_area = web_area + flange_area
    sharp_mx = web_area * (tw / 2.0) + flange_area * ((b + tw) / 2.0)

    # Each re-entrant fillet adds one quarter of a circle to the sharp L form.
    fillet_area = 0.5 * math.pi * r * r
    fillet_x = tw + r - (4.0 * r / (3.0 * math.pi))
    return (sharp_mx + fillet_area * fillet_x) / (sharp_area + fillet_area)


def _section(h, b, tw, tf, r, z0=None):
    if z0 is None:
        z0 = _parallel_leg_z0(h, b, tw, tf, r)
    return {
        "H": float(h),
        "B": float(b),
        "tw": float(tw),
        "tf": float(tf),
        "r": float(r),
        "Z0": float(z0),
    }


