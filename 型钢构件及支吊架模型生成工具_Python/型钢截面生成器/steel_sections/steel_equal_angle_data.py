def get_section(profile_name):
    if profile_name not in EQUAL_ANGLE_DATA:
        raise KeyError("Unknown equal-angle profile: {}".format(profile_name))
    return dict(EQUAL_ANGLE_DATA[profile_name])


def validate_section(section):
    b = float(section["B"])
    t = float(section["t"])
    r1 = float(section["r1"])
    r2 = float(section["r2"])
    if min(b, t, r1, r2) <= 0.0 or b <= t:
        raise ValueError("Invalid equal-angle dimensions.")
    if r1 >= b - t or r2 >= t:
        raise ValueError("Equal-angle fillet radius is too large.")
    return True


def nominal_area_mm2(section):
    """L shape with one re-entrant r1 and two r2 free-edge rounds."""
    validate_section(section)
    b = float(section["B"])
    t = float(section["t"])
    r1 = float(section["r1"])
    r2 = float(section["r2"])
    corner_factor = 1.0 - math.pi / 4.0
    return 2.0 * b * t - t * t + corner_factor * (r1 * r1 - 2.0 * r2 * r2)
