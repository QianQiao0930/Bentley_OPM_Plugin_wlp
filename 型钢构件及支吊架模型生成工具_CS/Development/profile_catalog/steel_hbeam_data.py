def _format_dimension(value):
    return "{:g}".format(value)


def _make_key(values):
    return "H{}x{}x{}x{}xr{}".format(
        _format_dimension(values["H"]),
        _format_dimension(values["B"]),
        _format_dimension(values["t1"]),
        _format_dimension(values["t2"]),
        _format_dimension(values["r"]),
    )


HBEAM_DATA = {}
PROFILE_NAMES = []
for _index, _row in enumerate(_ROWS, 1):
    _values = dict(zip(_FIELDS, _row))
    _key = _make_key(_values)
    if _key in HBEAM_DATA:
        _key = "{} #{}".format(_key, _index)
    _values["name"] = _key
    HBEAM_DATA[_key] = _values
    PROFILE_NAMES.append(_key)

DEFAULT_PROFILE = "H200x200x8x12xr13"
if DEFAULT_PROFILE not in HBEAM_DATA:
    DEFAULT_PROFILE = PROFILE_NAMES[0]


def profile_names():
    return tuple(PROFILE_NAMES)


def get_section(profile_name):
    if profile_name not in HBEAM_DATA:
        raise KeyError("H-beam profile was not found: {}".format(profile_name))
    return dict(HBEAM_DATA[profile_name])


def validate_section(section):
    """Validate geometric feasibility of the parallel-flange H section."""
    h = float(section["H"])
    b = float(section["B"])
    t1 = float(section["t1"])
    t2 = float(section["t2"])
    radius = float(section["r"])

    if h <= 0 or b <= 0 or t1 <= 0 or t2 <= 0 or radius < 0:
        raise ValueError("H, B, t1, t2 and r must be non-negative dimensions.")
    if h <= 2.0 * t2:
        raise ValueError("H must be greater than twice flange thickness t2.")
    if b <= t1:
        raise ValueError("B must be greater than web thickness t1.")
    if radius > (b - t1) / 2.0 or radius > (h - 2.0 * t2) / 2.0:
        raise ValueError("Root radius r is too large for the H-beam dimensions.")
    return True


def nominal_area_mm2(section):
    """Parallel-flange H geometry: rectangles plus four root fillets."""
    validate_section(section)
    h = float(section["H"])
    b = float(section["B"])
    t1 = float(section["t1"])
    t2 = float(section["t2"])
    radius = float(section["r"])
    return 2.0 * b * t2 + (h - 2.0 * t2) * t1 + (4.0 - math.pi) * radius * radius
