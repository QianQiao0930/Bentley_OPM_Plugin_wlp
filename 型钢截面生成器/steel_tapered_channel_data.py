TAPERED_CHANNEL_DATA = dict((name, _section(values)) for name, *values in _ROWS)
PROFILE_NAMES = tuple(name for name, *values in _ROWS)
DEFAULT_PROFILE = "20a"


def profile_names():
    return PROFILE_NAMES


def get_section(profile_name):
    if profile_name not in TAPERED_CHANNEL_DATA:
        raise KeyError("Unknown tapered-channel profile: {}".format(profile_name))
    return dict(TAPERED_CHANNEL_DATA[profile_name])


def flange_thicknesses(section):
    """Return root and flange-tip thicknesses for the specified 1:10 slope."""
    extension = float(section["B"]) - float(section["tw"])
    half_change = extension / 20.0
    return float(section["tf"]) + half_change, float(section["tf"]) - half_change


def validate_section(section):
    h = float(section["H"])
    b = float(section["B"])
    tw = float(section["tw"])
    tf = float(section["tf"])
    r1 = float(section["r1"])
    r2 = float(section["r2"])
    root_t, edge_t = flange_thicknesses(section)
    if min(h, b, tw, tf, r1, r2) <= 0.0:
        raise ValueError("H, B, tw, tf, r1 and r2 must be positive.")
    if b <= tw or edge_t <= 0.0 or h <= 2.0 * root_t:
        raise ValueError("Invalid tapered-channel dimensions.")
    if r1 >= min(h - 2.0 * root_t, b - tw) or r2 >= min(edge_t, b - tw):
        raise ValueError("Tapered-channel fillet radius is too large.")
    return True


def nominal_area_mm2(section):
    """GB/T Table 4 nominal area formula for a 1:10 tapered channel."""
    validate_section(section)
    h = float(section["H"])
    b = float(section["B"])
    tw = float(section["tw"])
    tf = float(section["tf"])
    r1 = float(section["r1"])
    r2 = float(section["r2"])
    return h * tw + 2.0 * tf * (b - tw) + 0.349 * (r1 * r1 - r2 * r2)
