IBEAM_DATA = dict((row[0], _section(*row[1:])) for row in _ROWS)
DEFAULT_PROFILE = "20a"


def profile_names():
    return tuple(row[0] for row in _ROWS)


def get_section(profile_name):
    try:
        section = dict(IBEAM_DATA[profile_name])
    except KeyError:
        raise ValueError("Unsupported I-beam profile: {0}".format(profile_name))
    validate_section(section)
    return section


def validate_section(section):
    required = ("H", "B", "tw", "tf", "r1", "r2", "A", "mass")
    missing = [key for key in required if key not in section]
    if missing:
        raise ValueError("Missing I-beam data: {0}".format(", ".join(missing)))

    h, b, tw, tf, r1, r2 = (section[key] for key in ("H", "B", "tw", "tf", "r1", "r2"))
    if min(h, b, tw, tf, r1, r2) <= 0.0:
        raise ValueError("I-beam dimensions must be positive.")
    if b <= tw:
        raise ValueError("B must be greater than tw.")

    half_extension = (b - tw) / 2.0
    edge_thickness = tf - half_extension / 12.0
    root_thickness = tf + half_extension / 12.0
    if edge_thickness <= 0.0 or h <= 2.0 * root_thickness:
        raise ValueError("I-beam dimensions cannot form a valid 1:6 tapered flange.")


def nominal_area_mm2(section):
    """GB/T 706 Table 4 area formula, using r1=inner and r2=leg-end radius."""
    validate_section(section)
    return (
        section["H"] * section["tw"]
        + 2.0 * section["tf"] * (section["B"] - section["tw"])
        + 0.577 * (section["r1"] ** 2 - section["r2"] ** 2)
    )

