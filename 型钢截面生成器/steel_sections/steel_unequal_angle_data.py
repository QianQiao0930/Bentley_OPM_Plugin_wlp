def _format_dimension(value):
    return "{:g}".format(value)


def _section(model, values):
    section = dict(zip(_FIELDS, map(float, values)))
    section["model"] = model
    section["r2"] = section["t"] / 3.0
    section["X0"] = section["X0_cm"] * 10.0
    section["Y0"] = section["Y0_cm"] * 10.0
    section["name"] = "L{}x{}x{}".format(
        _format_dimension(section["BL"]),
        _format_dimension(section["BS"]),
        _format_dimension(section["t"]),
    )
    return section


def validate_section(section):
    try:
        bl = float(section["BL"])
        bs = float(section["BS"])
        t = float(section["t"])
        r1 = float(section["r1"])
        r2 = float(section["r2"])
    except (KeyError, TypeError, ValueError):
        raise ValueError("Unequal-angle section requires BL, BS, t, r1 and r2.")
    if min(bl, bs, t, r1, r2) <= 0.0:
        raise ValueError("Unequal-angle dimensions must be positive.")
    if bl <= bs:
        raise ValueError("Unequal angle requires BL to be greater than BS.")
    if bs <= t:
        raise ValueError("Unequal-angle short leg must exceed thickness.")
    if r1 >= min(bl - t, bs - t):
        raise ValueError("Unequal-angle inner fillet r1 is too large.")
    if r2 >= t:
        raise ValueError("Unequal-angle toe fillet r2 is too large.")


UNEQUAL_ANGLE_DATA = OrderedDict(
    (section["name"], section)
    for model, values in _ROWS
    for section in (_section(model, values),)
)
PROFILE_NAMES = tuple(UNEQUAL_ANGLE_DATA.keys())
DEFAULT_PROFILE = "L63x40x5"


def profile_names():
    return PROFILE_NAMES


def get_section(profile_name):
    try:
        return dict(UNEQUAL_ANGLE_DATA[profile_name])
    except KeyError:
        raise KeyError("Unknown unequal-angle profile: {}".format(profile_name))


def nominal_area_mm2(section):
    """Nominal area including one r1 and two r2 rolling fillets."""
    validate_section(section)
    bl = float(section["BL"])
    bs = float(section["BS"])
    t = float(section["t"])
    r1 = float(section["r1"])
    r2 = float(section["r2"])
    corner_factor = 1.0 - math.pi / 4.0
    return bl * t + bs * t - t * t + corner_factor * (r1 * r1 - 2.0 * r2 * r2)
